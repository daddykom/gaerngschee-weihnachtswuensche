import { createFeature, createReducer, on } from '@ngrx/store';
import { AuthActions } from './auth.actions';
import { AuthState, initialState, loggedOutState } from './auth.state';
import { SessionActions } from './session.actions';

export const authFeature = createFeature({
  name: 'auth',
  reducer: createReducer<AuthState>(
    initialState,
    on(AuthActions.login, (state) => ({
      ...state,
      loading: true,
      errorCode: null,
      email: null,
      fairgateUserExists: null,
      fairgateStatus: null,
      childrenCount: null,
      adultsCount: null,
      salutation: null,
      firstAccess: false,
    })),
    on(AuthActions.checkEmail, (state) => ({
      ...state,
      emailCheckLoading: true,
      emailCheckMode: null,
      emailCheckEmail: null,
      emailCheckYear: null,
      emailCheckErrorCode: null,
    })),
    on(AuthActions.checkEmailSuccess, (state, { email, mode, processingYear }) => ({
      ...state,
      emailCheckLoading: false,
      emailCheckMode: mode,
      emailCheckEmail: email,
      emailCheckYear: processingYear,
      emailCheckErrorCode: null,
    })),
    on(AuthActions.checkEmailFailure, (state, { errorCode }) => ({
      ...state,
      emailCheckLoading: false,
      emailCheckMode: null,
      emailCheckErrorCode: errorCode,
    })),
    on(AuthActions.loginSuccess, (state, { userId, group, requiredPasswordReset, email }) => ({
      ...state,
      userId,
      group,
      requiredPasswordReset,
      loading: false,
      errorCode: null,
      email: email ?? state.email,
      firstAccess: false,
    })),
    on(AuthActions.loginFailure, (state, { errorCode }) => ({
      ...state,
      userId: null,
      group: null,
      requiredPasswordReset: false,
      loading: false,
      errorCode,
      email: null,
      fairgateUserExists: null,
      fairgateStatus: null,
      childrenCount: null,
      adultsCount: null,
      salutation: null,
    })),
    on(AuthActions.registrationLogin, (state) => ({
      ...state,
      registrationLoginLoading: true,
      registrationLoginErrorCode: null,
    })),
    on(AuthActions.registrationLoginSuccess, (state, result) => ({
      ...state,
      userId: result.userId,
      email: result.email,
      group: result.group,
      registrationLoginLoading: false,
      registrationLoginErrorCode: null,
      fairgateUserExists: result.fairgateUserExists,
      fairgateStatus: result.fairgateStatus ?? null,
      childrenCount: result.childrenCount,
      adultsCount: result.adultsCount,
      salutation: result.salutation,
      firstAccess: result.firstAccess,
    })),
    on(AuthActions.registrationLoginFailure, (state, { errorCode }) => ({
      ...state,
      userId: null,
      group: null,
      registrationLoginLoading: false,
      registrationLoginErrorCode: errorCode,
      fairgateUserExists: null,
      fairgateStatus: null,
      childrenCount: null,
      adultsCount: null,
      salutation: null,
      firstAccess: false,
    })),
    on(AuthActions.passwordChangeSuccess, (state) => ({
      ...state,
      requiredPasswordReset: false,
      passwordChangeLoading: false,
      passwordChangeErrorCode: null,
      firstAccess: false,
    })),
    on(AuthActions.passwordChange, (state) => ({
      ...state,
      passwordChangeLoading: true,
      passwordChangeErrorCode: null,
    })),
    on(AuthActions.passwordChangeFailure, (state, { errorCode }) => ({
      ...state,
      passwordChangeLoading: false,
      passwordChangeErrorCode: errorCode,
    })),
    on(AuthActions.logoutRequested, () => loggedOutState),
    on(SessionActions.statusLoaded, (state, { expiresAt, secondsRemaining }) => ({
      ...state,
      sessionExpiresAt: expiresAt,
      sessionSecondsRemaining: secondsRemaining,
      sessionWarningVisible: secondsRemaining <= 60,
    })),
    on(SessionActions.refreshRequested, (state) => ({ ...state, sessionRefreshLoading: true })),
    on(SessionActions.refreshSucceeded, (state, { expiresAt, secondsRemaining }) => ({
      ...state,
      sessionExpiresAt: expiresAt,
      sessionSecondsRemaining: secondsRemaining,
      sessionWarningVisible: false,
      sessionRefreshLoading: false,
    })),
    on(SessionActions.refreshFailed, (state) => ({ ...state, sessionRefreshLoading: false })),
    on(SessionActions.countdownStarted, (state) => ({ ...state, sessionWarningVisible: true })),
    on(SessionActions.countdownTick, (state, { secondsRemaining }) => ({
      ...state,
      sessionSecondsRemaining: secondsRemaining,
    })),
    on(SessionActions.countdownStopped, (state) => ({ ...state, sessionWarningVisible: false })),
  ),
});

export const {
  name: authFeatureName,
  reducer: authReducer,
  selectAuthState,
  selectUserId: selectAuthUserId,
  selectGroup: selectAuthGroup,
  selectRequiredPasswordReset: selectAuthRequiredPasswordReset,
  selectPasswordChangeLoading: selectAuthPasswordChangeLoading,
  selectPasswordChangeErrorCode: selectAuthPasswordChangeErrorCode,
  selectLoading: selectAuthLoading,
  selectErrorCode: selectAuthErrorCode,
  selectRegistrationLoginLoading: selectAuthRegistrationLoginLoading,
  selectRegistrationLoginErrorCode: selectAuthRegistrationLoginErrorCode,
  selectFirstAccess: selectAuthFirstAccess,
  selectFairgateUserExists: selectAuthFairgateUserExists,
  selectFairgateStatus: selectAuthFairgateStatus,
  selectChildrenCount: selectAuthChildrenCount,
  selectAdultsCount: selectAuthAdultsCount,
  selectSalutation: selectAuthSalutation,
  selectSessionExpiresAt: selectAuthSessionExpiresAt,
  selectSessionSecondsRemaining: selectAuthSessionSecondsRemaining,
  selectSessionWarningVisible: selectAuthSessionWarningVisible,
  selectSessionRefreshLoading: selectAuthSessionRefreshLoading,
  selectEmail: selectAuthEmail,
} = authFeature;

