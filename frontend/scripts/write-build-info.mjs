import { execFileSync } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const frontendDirectory = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const git = (...args) =>
  execFileSync('git', args, {
    cwd: frontendDirectory,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'ignore'],
  }).trim();

export function createBuildInfo({
  appVersion = '',
  describe = () => git('describe', '--tags', '--match', 'v[0-9]*', '--abbrev=0'),
} = {}) {
  // The installed source's release is independent of the identity of this build.
  const release = (appVersion.trim() || describe().replace(/^v/, '')).trim();
  if (!/^\d+\.\d+\.\d+(?:\+\d+)?$/.test(release)) {
    throw new Error('A release tag or an explicit APP_VERSION is required.');
  }
  return { appVersion: release, buildId: randomUUID() };
}

export function writeBuildInfo(directory, info) {
  rmSync(resolve(directory, 'public/version.json'), { force: true });
  for (const [file, contents] of [
    ['public/build-info.json', `${JSON.stringify(info, null, 2)}\n`],
    [
      'src/generated/build-info.ts',
      `// Generated by scripts/write-build-info.mjs.\nexport const BUILD_INFO = ${JSON.stringify(info)} as const;\n`,
    ],
  ]) {
    const output = resolve(directory, file);
    mkdirSync(dirname(output), { recursive: true });
    writeFileSync(output, contents);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const info = createBuildInfo({ appVersion: process.env.APP_VERSION });
  writeBuildInfo(frontendDirectory, info);
  console.log(`Release ${info.appVersion}; build ${info.buildId}`);
}
